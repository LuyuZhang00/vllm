// 中文注释：模块功能概述
// =========================================================================
// exception.hpp 提供逻辑蕴含（Implication）运算宏
//
// 逻辑蕴含 p => q 等价于 !p || q
// 真值表：
//   p   q   p=>q
//   T   T    T
//   T   F    F
//   F   T    T
//   F   F    T
//
// 使用场景：
// - 前置条件检查：如果条件 p 成立，则 q 必须也成立
// - 断言：用于表达复杂的约束关系
// =========================================================================

// 中文注释：逻辑蕴含宏
// VLLM_IMPLIES(p, q) 返回 true，当且仅当 p 为 false 或 q 为 true
// 等价于 "如果 p，则 q"
//
// 示例：
//   VLLM_IMPLIES(is_floating_point(), has_mantissa())
//   表示：如果是浮点类型，则必须有尾数
#define VLLM_IMPLIES(p, q) (!(p) || (q))
